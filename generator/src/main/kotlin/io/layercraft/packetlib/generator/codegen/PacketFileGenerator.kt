package io.layercraft.packetlib.generator.codegen

import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.BYTE_ARRAY
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STAR
import com.squareup.kotlinpoet.TypeSpec
import io.layercraft.packetlib.generator.MinecraftData
import io.layercraft.packetlib.generator.protodef.ContainerType
import io.layercraft.packetlib.generator.protodef.ProtoTypeParser
import io.layercraft.packetlib.generator.protodef.TypeResolver
import io.layercraft.packetlib.generator.protodef.UnsupportedProtoException
import kotlinx.serialization.json.JsonElement

enum class Direction(val key: String, val packageSegment: String) {
    CLIENTBOUND("toClient", "clientbound"),
    SERVERBOUND("toServer", "serverbound"),
    ;

    val interfaceType: ClassName
        get() = if (this == CLIENTBOUND) Runtime.CLIENT_BOUND_PACKET else Runtime.SERVER_BOUND_PACKET
}

data class PacketDefinition(
    val id: Int,
    val protoName: String,
    val className: String,
    val state: String,
    val direction: Direction,
    val fields: JsonElement?,
)

data class GeneratedPacket(
    val definition: PacketDefinition,
    val className: ClassName,
    val fallbackReason: String?,
)

/**
 * Generates one Kotlin file per packet: a data class implementing the packet interface with a
 * companion `PacketSerializer`. Falls back to a raw payload packet when the ProtoDef tree uses
 * constructs the generator cannot express.
 */
class PacketFileGenerator(
    private val versionPackage: String,
    private val protocolNumber: Int,
    private val folder: String,
) {

    fun generate(definition: PacketDefinition, resolver: TypeResolver): Pair<FileSpec, GeneratedPacket> {
        val packageName = "${Runtime.PACKETS_PACKAGE}.$versionPackage.${definition.state}.${definition.direction.packageSegment}"
        val className = ClassName(packageName, definition.className)

        val (typeSpecs, fallbackReason) = try {
            buildTypedPacket(definition, resolver, className) to null
        } catch (e: UnsupportedProtoException) {
            listOf(buildFallbackPacket(definition, className, e.reason)) to e.reason
        }

        val file = FileSpec.builder(className)
            .addFileComment("Generated by the packetlib generator from minecraft-data. Do not edit manually.")
            .addAnnotation(
                AnnotationSpec.builder(Suppress::class)
                    .addMember("%S, %S, %S, %S, %S", "NAME_SHADOWING", "unused", "UNUSED_ANONYMOUS_PARAMETER", "KDocUnresolvedReference", "RedundantSuppression")
                    .useSiteTarget(AnnotationSpec.UseSiteTarget.FILE)
                    .build(),
            )
            .indent("    ")
        typeSpecs.forEach { file.addType(it) }

        return file.build() to GeneratedPacket(definition, className, fallbackReason)
    }

    private fun packetKdoc(definition: PacketDefinition, note: String? = null): String {
        val idHex = "0x%02x".format(definition.id)
        return buildString {
            append("${definition.protoName} | $idHex | ${definition.state} | ${definition.direction.packageSegment}\n")
            if (note != null) append("\n$note\n")
            append("\nSource: [${folder}/protocol.json](${MinecraftData.sourceUrl(folder)})\n")
        }
    }

    private fun buildTypedPacket(definition: PacketDefinition, resolver: TypeResolver, className: ClassName): List<TypeSpec> {
        val fields = definition.fields ?: throw UnsupportedProtoException("packet type is not declared")
        val container = resolver.deepResolve(ProtoTypeParser.parse(fields)) as? ContainerType
            ?: throw UnsupportedProtoException("packet type is not a container")

        val bodyGen = PacketBodyGen(resolver, protocolNumber, className.packageName)
        bodyGen.claimClassName(className.simpleName)
        val body = bodyGen.genPacketBody(container, className.simpleName)

        val classBuilder = TypeSpec.classBuilder(className)
            .addSuperinterface(definition.direction.interfaceType)
            .addKdoc(packetKdoc(definition))

        if (body.properties.isNotEmpty()) {
            classBuilder.addModifiers(KModifier.DATA)
            val constructor = FunSpec.constructorBuilder()
            for (p in body.properties) {
                constructor.addParameter(p.name, p.typeName)
                classBuilder.addProperty(PropertySpec.builder(p.name, p.typeName).initializer("%N", p.name).build())
                classBuilder.addKdoc("@param %N %L\n", p.name, p.protoName)
            }
            classBuilder.primaryConstructor(constructor.build())
        }

        val deserialize = FunSpec.builder("deserialize")
            .addModifiers(KModifier.OVERRIDE)
            .addParameter("input", Runtime.DESERIALIZER.parameterizedBy(STAR))
            .returns(className)
            .addCode(body.read)
            .addCode("return %T(", className)
        body.properties.forEachIndexed { i, p -> deserialize.addCode(if (i == 0) "%N" else ",·%N", p.name) }
        deserialize.addCode(")\n")

        val serialize = FunSpec.builder("serialize")
            .addModifiers(KModifier.OVERRIDE)
            .addParameter("output", Runtime.SERIALIZER.parameterizedBy(STAR))
            .addParameter("value", className)
            .addCode(body.write)

        classBuilder.addType(
            TypeSpec.companionObjectBuilder()
                .addSuperinterface(Runtime.PACKET_SERIALIZER.parameterizedBy(className))
                .addFunction(deserialize.build())
                .addFunction(serialize.build())
                .build(),
        )

        return listOf(classBuilder.build()) + bodyGen.extraTypes
    }

    private fun buildFallbackPacket(definition: PacketDefinition, className: ClassName, reason: String): TypeSpec {
        val note = "Raw fallback packet: the payload is kept as unparsed bytes because the " +
            "protocol definition uses unsupported constructs ($reason)."

        return TypeSpec.classBuilder(className)
            .addModifiers(KModifier.DATA)
            .addSuperinterface(definition.direction.interfaceType)
            .addKdoc(packetKdoc(definition, note))
            .addKdoc("@param raw the raw packet payload\n")
            .primaryConstructor(FunSpec.constructorBuilder().addParameter("raw", BYTE_ARRAY).build())
            .addProperty(PropertySpec.builder("raw", BYTE_ARRAY).initializer("raw").build())
            .addType(
                TypeSpec.companionObjectBuilder()
                    .addSuperinterface(Runtime.PACKET_SERIALIZER.parameterizedBy(className))
                    .addFunction(
                        FunSpec.builder("deserialize")
                            .addModifiers(KModifier.OVERRIDE)
                            .addParameter("input", Runtime.DESERIALIZER.parameterizedBy(STAR))
                            .returns(className)
                            .addCode("return %T(input.readRemainingByteArray())\n", className)
                            .build(),
                    )
                    .addFunction(
                        FunSpec.builder("serialize")
                            .addModifiers(KModifier.OVERRIDE)
                            .addParameter("output", Runtime.SERIALIZER.parameterizedBy(STAR))
                            .addParameter("value", className)
                            .addCode("output.writeRemainingByteArray(value.raw)\n")
                            .build(),
                    )
                    .build(),
            )
            .build()
    }
}
